-- Catálogo: trilhas e as aulas de cada uma.

create table trilha (
    id          bigint generated by default as identity primary key,
    slug        varchar(80)  not null unique,
    numero      integer      not null unique,
    nome        varchar(120) not null,
    ferramentas varchar(120) not null,
    aprende     varchar(600) not null,
    resultado   varchar(300) not null,
    foto        varchar(200)
);

create table aula (
    id               bigint generated by default as identity primary key,
    trilha_id        bigint       not null references trilha (id),
    ordem            integer      not null,
    titulo           varchar(160) not null,
    resumo           varchar(600),
    duracao_segundos integer,
    -- Identificador do vídeo no provedor (Bunny Stream ou Panda Video).
    video_id         varchar(120),
    unique (trilha_id, ordem)
);
