-- O catálogo deixa de ser "trilhas" e passa a ser cursos, com módulos e aulas.
-- Os 7 cursos iniciais são as antigas trilhas, com o mesmo número.

drop table plano_trilha;
drop table aula;
drop table trilha;

create table categoria (
    id        bigint generated by default as identity primary key,
    slug      varchar(80)  not null unique,
    nome      varchar(80)  not null,
    descricao varchar(300),
    ordem     integer      not null
);

create table instrutor (
    id       bigint generated by default as identity primary key,
    nome     varchar(120) not null,
    titulo   varchar(160),
    bio      varchar(1200),
    foto_url varchar(300)
);

create table curso (
    id                     bigint generated by default as identity primary key,
    slug                   varchar(120) not null unique,
    -- Aparece como expoente dourado na capa e no título.
    numero                 integer      not null unique,
    titulo                 varchar(160) not null,
    subtitulo              varchar(300) not null,
    descricao              varchar(8000),
    capa_url               varchar(300),
    capa_alt               varchar(300),
    video_previa_id        varchar(120),
    nivel                  varchar(20)  not null,
    idioma                 varchar(10)  not null,
    categoria_id           bigint       not null references categoria (id),
    resultado_final        varchar(300) not null,
    status                 varchar(20)  not null,
    publicado_em           timestamp with time zone,
    atualizado_em          timestamp with time zone not null,
    nota_media             numeric(3, 2) not null default 0,
    total_avaliacoes       integer      not null default 0,
    total_alunos           integer      not null default 0,
    certificado_habilitado boolean      not null default true,
    seo_titulo             varchar(160),
    seo_descricao          varchar(300)
);

-- Listas do curso (ordem importa).
create table curso_ferramenta (
    curso_id bigint       not null references curso (id),
    ordem    integer      not null,
    texto    varchar(80)  not null,
    primary key (curso_id, ordem)
);
create table curso_aprendizado (
    curso_id bigint       not null references curso (id),
    ordem    integer      not null,
    texto    varchar(300) not null,
    primary key (curso_id, ordem)
);
create table curso_requisito (
    curso_id bigint       not null references curso (id),
    ordem    integer      not null,
    texto    varchar(300) not null,
    primary key (curso_id, ordem)
);
create table curso_publico (
    curso_id bigint       not null references curso (id),
    ordem    integer      not null,
    texto    varchar(300) not null,
    primary key (curso_id, ordem)
);

create table curso_instrutor (
    curso_id     bigint  not null references curso (id),
    instrutor_id bigint  not null references instrutor (id),
    ordem        integer not null,
    primary key (curso_id, ordem)
);

create table modulo (
    id        bigint generated by default as identity primary key,
    curso_id  bigint       not null references curso (id),
    ordem     integer      not null,
    titulo    varchar(160) not null,
    descricao varchar(600)
);

create table aula (
    id               bigint generated by default as identity primary key,
    modulo_id        bigint       not null references modulo (id),
    ordem            integer      not null,
    titulo           varchar(160) not null,
    tipo             varchar(20)  not null,
    resumo           varchar(600),
    conteudo         varchar(20000),
    -- Identificador do vídeo no provedor. Nunca sai em rota pública.
    video_id         varchar(120),
    duracao_segundos integer,
    previa           boolean      not null default false,
    legenda_url      varchar(300),
    publicada        boolean      not null default true
);

create table material (
    id            bigint generated by default as identity primary key,
    aula_id       bigint       not null references aula (id),
    nome          varchar(160) not null,
    arquivo_url   varchar(300) not null,
    tamanho_bytes bigint,
    tipo_mime     varchar(100)
);

-- Cursos liberados por plano.
create table plano_curso (
    plano_id varchar(40) not null references plano (id),
    curso_id bigint      not null references curso (id),
    primary key (plano_id, curso_id)
);

